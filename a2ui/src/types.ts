/*
 * ----------------------------------------------------------------------------
 * ⚓ COMPONENT: A2uiAdapter / Types
 * 📜 PURPOSE: Structural types for the A2UI host objects the adapter touches,
 *    and the generated descriptor. The adapter imports nothing from
 *    @a2ui/web_core at runtime (spec §4.1): it uses the context the host's
 *    renderer assigns, so these interfaces name only the members it calls.
 * 🔗 RELATES: [[A2uiAdapter]], [[AgentUiAdapterDescriptors]]
 * ⚡ FLOW: [host renderer] -> [ComponentContextLike] -> [element]
 * ----------------------------------------------------------------------------
 */

// @semantic-marker a2ui-adapter-types

/** A web_core subscription: the current value plus a way to stop. */
export interface Sub
{
    readonly value?: unknown;
    unsubscribe(): void;
}

/** The members of web_core's SurfaceModel the adapter uses. */
export interface SurfaceLike
{
    readonly id: string;
    /** The surface's components, which a layout's child slots refer to by id (ADR-238). */
    readonly componentsModel?: SurfaceComponentsLike;
    dispatchError(error: { code: string; message: string; path?: string }): Promise<void>;
}

/** The members of web_core's SurfaceComponentsModel the adapter uses (ADR-238). */
export interface SurfaceComponentsLike
{
    get(id: string): ComponentModelLike | undefined;
    readonly onCreated: { subscribe(listener: (model: ComponentModelLike) => void): Sub };
    readonly onDeleted: { subscribe(listener: (id: string) => void): Sub };
}

/** A catalog entry as the adapter reads it to render a child: a tag and the element class behind it. */
export interface CatalogEntryLike
{
    readonly tagName?: string;
    readonly element?: CustomElementConstructor;
}

/** The members of web_core's DataContext the adapter uses. */
export interface DataContextLike
{
    readonly surface?: SurfaceLike;
    readonly dataModel: unknown;
    readonly path: string;
    readonly explicitIndex?: number;
    readonly parent?: unknown;
    subscribeDynamicValue(value: unknown, onChange: (value: unknown) => void): Sub;
    resolveAction(action: unknown): unknown;
    set(path: string, value: unknown): void;
}

/** The members of web_core's ComponentModel the adapter uses. */
export interface ComponentModelLike
{
    readonly id: string;
    readonly type: string;
    readonly properties: Record<string, unknown>;
    readonly onUpdated: { subscribe(listener: () => void): Sub };
    /** The catalog the component was created from; a child's element comes from it (ADR-238). */
    readonly catalog?: { readonly components: { get(type: string): CatalogEntryLike | undefined } };
}

/** The members of web_core's ComponentContext the adapter uses. */
export interface ComponentContextLike
{
    readonly componentModel: ComponentModelLike;
    readonly surfaceComponents: unknown;
    readonly theme: unknown;
    readonly dataContext: DataContextLike;
    dispatchAction(action: unknown): Promise<void>;
}

/** How a changed data prop reaches the live component (spec §3.2). */
export type PropRoute =
    | { route: "slot"; slot: string; setter?: string }
    | { route: "state"; key: string }
    | { route: "value" }
    | { route: "create" };

/** An option path that holds one child component id, or a list of them (ADR-238). */
export interface ChildSlot
{
    path: string;
    cardinality: "one" | "many";
}

/** One emits channel, named for the catalog (spec §5.7). */
export interface AdapterEvent
{
    channel: string;
    option?: string | null;
    actionProp: string;
    payloadInValue: boolean;
}

/** One provider: a callback that asks the agent for data (ADR-225, spec §3). */
export interface AdapterProvider
{
    /** The factory option the callback is passed as, e.g. "onLoadChildren". */
    option: string;
    /** The catalog request name; the request is written to <eventData>/<request>. */
    request: string;
    /** The on<Request> action prop the adapter dispatches. */
    actionProp: string;
    /** The <request>Result prop whose bound path the agent answers at. */
    resultProp: string;
    /** "latest": a newer request replaces a waiting one. "queue": every request, in order. */
    concurrency: "latest" | "queue";
}

/** One catalog component, as generated by scripts/agentui/adapter-descriptors.mjs (spec §3.1). */
export interface AdapterDescriptor
{
    name: string;
    tagName: string;
    factory: `create${string}`;
    factoryStyle: "container-first" | "options-first" | "options-only";
    containerOption?: string;
    containerAs?: "element" | "id";
    mountMethod: "auto" | "show" | "getElement";
    conformance: "display" | "field" | "surface";
    /** The component's own script and stylesheet, and what loads before them (ADR-230). */
    assets: { js: string; css?: string; deps?: { path: string; integrity?: string }[] };
    props: Record<string, PropRoute>;
    twoWay: boolean;
    changeOption?: string;
    /** The manifest's protocol.change mapping (ADR-222); absent when onChange passes the value itself. */
    change?: { valueFrom: string } | { cleared: null };
    /**
     * Set for a manifest with `presentation: "overlay"` (#41): the component
     * positions itself absolutely inside its container, so the adapter gives
     * the container `position: relative` and the manifest's default height.
     */
    overlay?: { height: number };
    /**
     * Set for a layout (manifest category "layout", ADR-238): it fills its
     * container, so the adapter gives the container a definite height, the
     * manifest's default unless the host sets --outcrop-layout-height on the
     * element.
     */
    fill?: { height: number };
    /**
     * The manifest's protocol.fixed (ADR-235): options passed on every mount
     * with these values. The catalog leaves them out, so no agent prop can
     * set them.
     */
    fixed?: Record<string, unknown>;
    /** Option paths that hold child components (ADR-238). */
    children?: ChildSlot[];
    /**
     * The manifest's stateKeys, when it declares any: the only keys of
     * getState() a rebuild carries across (ADR-240). A key that is also an
     * option would otherwise undo the agent's change that caused the rebuild.
     */
    stateKeys?: string[];
    events: AdapterEvent[];
    providers: AdapterProvider[];
    dates: string[];
}

/** A compiled literal-arm validator (Ajv standalone). */
export type Validator = (value: unknown) => boolean;

/** Validators keyed "<Name>.<prop>". */
export type Validators = Readonly<Record<string, Validator>>;
